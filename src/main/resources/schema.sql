-- Estrutura do banco do Studio Elen Gomes.
-- O Spring executa este arquivo toda vez que o backend sobe (spring.sql.init).
-- Por usar "IF NOT EXISTS", ele só cria o que ainda não existe: num banco novo
-- do Neon cria todas as tabelas; num banco já criado não altera nada.

CREATE TABLE IF NOT EXISTS clientes (
    id              VARCHAR(36)  PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    telefone        VARCHAR(30)  NOT NULL,
    email           VARCHAR(150),
    data_nascimento DATE,
    criado_em       TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS idx_clientes_nome ON clientes (LOWER(nome));

CREATE TABLE IF NOT EXISTS servicos (
    id                VARCHAR(36)    PRIMARY KEY,
    nome              VARCHAR(150)   NOT NULL,
    descricao         TEXT,
    duracao_min       INTEGER        NOT NULL CHECK (duracao_min > 0),
    preco             NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    ativo             BOOLEAN        NOT NULL DEFAULT TRUE,
    requer_retorno    BOOLEAN        NOT NULL DEFAULT FALSE,
    dias_para_retorno INTEGER
);

CREATE TABLE IF NOT EXISTS agendamentos (
    id          VARCHAR(36) PRIMARY KEY,
    cliente_id  VARCHAR(36) NOT NULL REFERENCES clientes (id),
    servico_id  VARCHAR(36) NOT NULL REFERENCES servicos (id),
    data_hora   TIMESTAMP(6) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'AGENDADO'
                CHECK (status IN ('SOLICITADO', 'AGENDADO', 'CONFIRMADO', 'CONCLUIDO', 'CANCELADO')),
    observacoes TEXT,
    criado_em   TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS idx_agendamentos_data_hora ON agendamentos (data_hora);
CREATE INDEX IF NOT EXISTS idx_agendamentos_cliente ON agendamentos (cliente_id);

CREATE TABLE IF NOT EXISTS pagamentos (
    id              VARCHAR(36)    PRIMARY KEY,
    agendamento_id  VARCHAR(36)    NOT NULL UNIQUE REFERENCES agendamentos (id),
    valor           NUMERIC(10, 2) NOT NULL CHECK (valor >= 0),
    forma_pagamento VARCHAR(20)    NOT NULL
                    CHECK (forma_pagamento IN ('DINHEIRO', 'PIX', 'CARTAO_DEBITO', 'CARTAO_CREDITO')),
    pago_em         TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS idx_pagamentos_pago_em ON pagamentos (pago_em);

CREATE TABLE IF NOT EXISTS remarcacoes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id     VARCHAR(36)  NOT NULL REFERENCES agendamentos (id) ON DELETE CASCADE,
    data_hora_anterior TIMESTAMP(6) NOT NULL,
    nova_data_hora     TIMESTAMP(6) NOT NULL,
    motivo             VARCHAR(255),
    criado_em          TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_remarcacoes_agendamento ON remarcacoes (agendamento_id);

CREATE TABLE IF NOT EXISTS notificacoes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id VARCHAR(36) REFERENCES agendamentos (id) ON DELETE CASCADE,
    cliente_id     VARCHAR(36) REFERENCES clientes (id) ON DELETE CASCADE,
    tipo           VARCHAR(30),
    status         VARCHAR(20),
    canal          VARCHAR(20),
    mensagem       TEXT,
    enviada_em     TIMESTAMP(6),
    criada_em      TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS idx_notificacoes_agendamento ON notificacoes (agendamento_id, tipo, canal, status);

CREATE TABLE IF NOT EXISTS fichas_capilares (
    id                 VARCHAR(36) PRIMARY KEY,
    cliente_id         VARCHAR(36) NOT NULL UNIQUE REFERENCES clientes (id) ON DELETE CASCADE,
    tipo_cabelo        VARCHAR(100),
    historico_quimicos TEXT,
    alergias           TEXT,
    observacoes        TEXT,
    atualizado_em      TIMESTAMP(6)
);

